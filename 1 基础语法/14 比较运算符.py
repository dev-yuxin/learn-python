# ==, !=, <, <=, >, >=
# 本质上是底层重写了 __eq__(), __gt__(), __ge__(), __lt__(), __le__() 方法

# 数值型大小比较
print(9 > 3)
# 字符串之间按字典序比较
print("123" < "45")

# 允许连续比较
# 1 < 2 and 2 < 3
print(1 < 2 < 3)

# 这里先调用 "123".__eq__(123) NotImplemented
# 再调用 123.__eq__("123") NotImplemented
# 最后再调用 "123" is 123 返回 False
print("123" == 123)

# 区分 is 和 ==
# is 是比较引用地址值
# == 是调用 __eq__
